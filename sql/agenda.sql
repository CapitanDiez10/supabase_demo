-- =========================================================
-- Tabla contactos (ya existe en Supabase, NO se borra)
-- =========================================================
CREATE TABLE IF NOT EXISTS contactos(
    id_contacto BIGINT generated by default as identity not null PRIMARY KEY,
    nombre text not null,
    email text not null,
    telefono text not null
);

-- Agrega la columna foto SIN borrar ni cambiar los contactos que ya existen.
-- A los contactos actuales se les pone 'default.png'.
ALTER TABLE contactos ADD COLUMN IF NOT EXISTS foto text not null default 'default.png';

-- =========================================================
-- Tabla sesiones_abiertas (nueva)
-- Guarda los tokens JWT de los usuarios que iniciaron sesión
-- =========================================================
CREATE TABLE IF NOT EXISTS sesiones_abiertas(
    id_sesion BIGINT generated by default as identity not null PRIMARY KEY,
    token text not null,
    fecha timestamptz not null default now()
);

-- Igual que contactos: se desactiva RLS para que la app pueda leer/escribir
-- con la llave anon (solo para la práctica)
ALTER TABLE sesiones_abiertas DISABLE ROW LEVEL SECURITY;

